export interface QuestionQcm {
  theme: ThemeQcmId;
  question: string;
  options: string[];
  /** Indices des bonnes réponses. */
  bonnes: number[];
  explication: string;
  /** Question dont les réponses sont celles de la note de cadrage officielle. */
  officielle: boolean;
}

function q(
  theme: ThemeQcmId,
  question: string,
  options: string[],
  bonnes: string,
  explication: string,
  officielle = false,
): QuestionQcm {
  return {
    theme,
    question,
    options,
    bonnes: [...bonnes].map((l) => l.charCodeAt(0) - 65),
    explication,
    officielle,
  };
}

